export const SOLAR_SYSTEM_DATA: SolarSystemDataset = {
  revision: '2026-08-15-rounded-v1',
  dataAsOf: '2026-08-15',
  bodies: SOLAR_SYSTEM_BODIES,
};

export const celestialBodyById = new Map(
  SOLAR_SYSTEM_BODIES.map((body) => [body.id, body]),
);

export const majorMoonsByParentId = new Map<string, readonly CelestialBodyData[]>();
for (const body of SOLAR_SYSTEM_BODIES) {
  if (body.type !== 'moon' || body.parentId === undefined) {
    continue;
  }
  const existing = majorMoonsByParentId.get(body.parentId) ?? [];
  majorMoonsByParentId.set(body.parentId, [...existing, body]);
}

export function getCelestialBody(id: string): CelestialBodyData | undefined {
  return celestialBodyById.get(id);
}

export function getMajorMoons(parentId: string): readonly CelestialBodyData[] {
  return majorMoonsByParentId.get(parentId) ?? [];
}

export function getHeliocentricBodies(): readonly CelestialBodyData[] {
  return SOLAR_SYSTEM_BODIES.filter(
    (body) => body.type === 'planet' || body.type === 'dwarf-planet',
  );
}
